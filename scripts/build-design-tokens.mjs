#!/usr/bin/env node
/* Emit a W3C design-tokens (DTCG) file for each Signature template, derived
 * from that template's tokens.css.
 *
 * Generated rather than hand-kept on purpose: tokens.css is what the template
 * actually renders from, so anything written separately is a second copy of
 * the truth that silently drifts the first time a colour changes. Run this
 * after editing any tokens.css:
 *
 *   npm run build:tokens
 *
 * Values are complete. `$description` is deliberately absent — the prose lives
 * in each template's style reference, and inventing it here would put words in
 * the design's mouth.
 */

import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const TPL = resolve(here, "../src/templates");

// Any template folder carrying a tokens.css. Discovered rather than listed, so
// adding or dropping a Signature template needs no edit here.
const SIGNATURE = readdirSync(TPL, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(TPL, d.name, "tokens.css")))
  .map((d) => d.name)
  .sort();

/* --var-name -> [group, key] for the DTCG tree, plus its $type. Anything that
   does not match a prefix is dropped: @theme and DTCG describe design values,
   not the layout one-offs (--page-max-width, --section-gap) that only mean
   something inside the stylesheet. */
const GROUPS = [
  { prefix: "--color-", group: "color", type: "color" },
  { prefix: "--gradient-", group: "gradient", type: "color" },
  { prefix: "--surface-", group: "surface", type: "color" },
  { prefix: "--font-weight-", group: "fontWeight", type: "fontWeight" },
  { prefix: "--font-", group: "font", type: "fontFamily" },
  { prefix: "--text-", group: "fontSize", type: "dimension" },
  { prefix: "--leading-", group: "lineHeight", type: "number" },
  { prefix: "--tracking-", group: "letterSpacing", type: "dimension" },
  { prefix: "--spacing-", group: "spacing", type: "dimension" },
  { prefix: "--radius-", group: "radius", type: "dimension" },
];

function parseTokens(css) {
  const body = css.slice(css.indexOf("{") + 1, css.lastIndexOf("}"));
  const out = {};
  for (const line of body.split("\n")) {
    const m = line.match(/^\s*(--[\w-]+):\s*(.+);\s*$/);
    if (!m) continue;
    const [, name, value] = m;
    // longest prefix wins, so --font-weight-* never lands in `font`
    const hit = GROUPS.filter((g) => name.startsWith(g.prefix)).sort(
      (a, b) => b.prefix.length - a.prefix.length
    )[0];
    if (!hit) continue;
    const key = name.slice(hit.prefix.length);
    (out[hit.group] ||= {})[key] = {
      $value: hit.type === "number" ? Number(value) : value,
      $type: hit.type,
    };
  }
  return out;
}

let count = 0;
for (const slug of SIGNATURE) {
  const src = join(TPL, slug, "tokens.css");
  if (!existsSync(src)) {
    console.warn(`! ${slug}: no tokens.css, skipped`);
    continue;
  }
  const tokens = parseTokens(readFileSync(src, "utf8"));
  tokens.$extensions = {
    "com.tamerao.template": {
      template: slug,
      source: "tokens.css",
      note: "Generated by npm run build:tokens. Edit tokens.css, not this file.",
    },
  };
  const dest = join(TPL, slug, "tokens.json");
  writeFileSync(dest, JSON.stringify(tokens, null, 2) + "\n");
  const n = Object.values(tokens).filter((v) => v && !v.template).reduce(
    (a, g) => a + Object.keys(g).length,
    0
  );
  console.log(`  ${slug.padEnd(9)} -> src/templates/${slug}/tokens.json  ${n} tokens`);
  count++;
}
console.log(`${count} token files written`);
